'use client';

import { useRef, useState, useCallback, useEffect } from 'react';
import { useChat } from '@ai-sdk/react';
import {
  DefaultChatTransport,
  lastAssistantMessageIsCompleteWithToolCalls,
} from 'ai';
import type { ChatMessage } from '@/lib/types';
import { useParams, useRouter, usePathname } from 'next/navigation';
import {
  Send,
  Square,
  AlertCircle,
  PanelRightIcon,
  PanelRightOpenIcon,
  PenSquareIcon,
} from 'lucide-react';
import { SiGooglegemini } from 'react-icons/si';

import { Button } from '@/components/ui/button';
import { cn } from '@/lib/utils';
import { ChatSidebar } from './chat-sidebar';
import { Messages } from './messages';
import { useScrollToBottom } from '@/hooks/use-scroll-to-bottom';
import { useChatHistory } from '@/features/chat/hooks/use-chat-history';
import useSWR from 'swr';
import Link from 'next/link';
import { authClient } from '@/lib/auth-client';

const fetcher = (url: string) => fetch(url).then((r) => r.json());

export default function ChatPage() {
  const params = useParams();
  const router = useRouter();
  const pathname = usePathname();
  const chatId = params?.id as string | undefined;
  const isNewChat = !chatId;
  const isNewChatPage = pathname === '/dashboard/chat';
  const [generatedId, setGeneratedId] = useState(() => crypto.randomUUID());
  const prevPathnameRef = useRef(pathname);
  const justCreatedChatRef = useRef(false);

  useEffect(() => {
    if (isNewChat && prevPathnameRef.current !== pathname) {
      setGeneratedId(crypto.randomUUID());
      justCreatedChatRef.current = false;
    }
    prevPathnameRef.current = pathname;
  }, [pathname, isNewChat]);

  const currentChatId = chatId ?? generatedId;
  const [sidebarCollapsed, setSidebarCollapsed] = useState(false);

  const { data: sessionData } = authClient.useSession();
  const organizationId =
    sessionData?.session?.activeOrganizationId ?? undefined;
  const { mutate: mutateChatHistory } = useChatHistory(organizationId);

  const { data: chatData, isLoading: isHistoryLoading } = useSWR(
    isNewChat ? null : `/api/messages?chatId=${chatId}`,
    fetcher,
    { revalidateOnFocus: false },
  );

  // Stable reference to avoid useChat re-syncing its internal state on every render.
  // Actual message loading for existing chats is handled by the setMessages effect below.
  const stableEmptyMessages = useRef<ChatMessage[]>([]).current;

  const {
    messages,
    setMessages,
    sendMessage,
    status,
    error,
    stop,
    regenerate,
  } = useChat<ChatMessage>({
    id: currentChatId,
    messages: stableEmptyMessages,
    generateId: () => crypto.randomUUID(),
    sendAutomaticallyWhen: lastAssistantMessageIsCompleteWithToolCalls,
    transport: new DefaultChatTransport({
      api: '/api/chat',
      prepareSendMessagesRequest: ({ id, messages }) => {
        const lastMessage = messages.at(-1);
        const isToolContinuation =
          lastMessage?.role !== 'user' ||
          messages.some((msg: any) =>
            msg.parts?.some(
              (p: any) => p.type === 'tool-call' || p.type === 'tool-result',
            ),
          );

        return {
          body: isToolContinuation
            ? { id, messages }
            : { id, message: lastMessage },
        };
      },
    }),
    onFinish: () => {
      // Revalidate sidebar to pick up the real title generated by the server.
      mutateChatHistory();
    },
  });

  const [input, setInput] = useState('');
  const textareaRef = useRef<HTMLTextAreaElement>(null);
  const {
    containerRef,
    endRef,
    isAtBottom,
    scrollToBottom,
    setStreaming,
    reset: resetScroll,
  } = useScrollToBottom();

  const isStreaming = status === 'streaming' || status === 'submitted';

  const prevChatIdRef = useRef(chatId);
  useEffect(() => {
    if (prevChatIdRef.current !== chatId) {
      prevChatIdRef.current = chatId;
      resetScroll();
    }
  }, [chatId, resetScroll]);

  useEffect(() => {
    if (chatData?.messages && !isNewChat && !justCreatedChatRef.current) {
      setMessages(chatData.messages);
    }
  }, [chatData?.messages, isNewChat, setMessages]);

  useEffect(() => {
    setStreaming(isStreaming);
  }, [isStreaming, setStreaming]);

  useEffect(() => {
    if (isNewChat) {
      setMessages([]);
    }
  }, [chatId, isNewChat, setMessages]);

  useEffect(() => {
    if (textareaRef.current) {
      textareaRef.current.style.height = 'auto';
      textareaRef.current.style.height = `${Math.min(textareaRef.current.scrollHeight, 200)}px`;
    }
  }, [input]);

  const handleSend = useCallback(() => {
    if (!input.trim() || status !== 'ready') return;
    sendMessage({ text: input });
    if (isNewChat) {
      justCreatedChatRef.current = true;
      router.replace(`/dashboard/chat/${currentChatId}`);

      // Optimistically add the new chat to the sidebar cache.
      // The chat doesn't exist in the DB yet (the /api/chat POST is still in-flight),
      // so we skip revalidation here. onFinish will revalidate to pick up the real title.
      mutateChatHistory(
        (currentData) => {
          if (!currentData || currentData.length === 0) {
            return [
              {
                chats: [
                  {
                    id: currentChatId,
                    title: 'New chat',
                    userId: '',
                    organizationId: '',
                    createdAt: new Date().toISOString(),
                  },
                ],
                hasMore: false,
              },
            ];
          }
          const firstPage = currentData[0];
          return [
            {
              ...firstPage,
              chats: [
                {
                  id: currentChatId,
                  title: 'New chat',
                  userId: '',
                  organizationId: '',
                  createdAt: new Date().toISOString(),
                },
                ...firstPage.chats,
              ],
            },
            ...currentData.slice(1),
          ];
        },
        { revalidate: false },
      );
    }
    setInput('');
  }, [
    input,
    status,
    sendMessage,
    isNewChat,
    currentChatId,
    router,
    mutateChatHistory,
  ]);

  const handleKeyDown = useCallback(
    (e: React.KeyboardEvent) => {
      if (e.key === 'Enter' && !e.shiftKey) {
        e.preventDefault();
        handleSend();
      }
    },
    [handleSend],
  );

  const hasMessages = messages.length > 0;

  return (
    <div className="h-full flex w-full flex-row overflow-hidden">
      <div
        className={cn(
          'flex min-w-0 min-h-0 overflow-hidden flex-col bg-sidebar transition-[width] duration-300 ease-[cubic-bezier(0.32,0.72,0,1)] ',
          sidebarCollapsed ? 'flex-1' : 'flex-1',
        )}
      >
        <header className="sticky top-0 flex h-14 items-center gap-2 bg-sidebar px-3">
          <div className="flex-1" />
          <Button
            size="icon"
            variant="ghost"
            className={cn(
              'h-8 w-8 shrink-0 cursor-pointer',
              !sidebarCollapsed && 'hidden',
            )}
            onClick={() => setSidebarCollapsed(false)}
          >
            <PanelRightIcon className="size-4 text-sidebar-foreground/60" />
          </Button>
        </header>

        <div className="relative flex min-h-0 flex-1 flex-col overflow-hidden bg-background md:rounded-tl-[12px] md:border-t md:border-l md:border-border/40">
          <Messages
            chatId={currentChatId}
            status={status}
            messages={messages}
            containerRef={containerRef as React.RefObject<HTMLDivElement>}
            endRef={endRef as React.RefObject<HTMLDivElement>}
            isAtBottom={isAtBottom}
            scrollToBottom={scrollToBottom}
            hasMessages={hasMessages}
            isHistoryLoading={isHistoryLoading}
            isNewChatPage={isNewChatPage}
          />

          {error && (
            <div className="shrink-0 flex items-center gap-2 mx-4 mb-1 px-3 py-1.5 rounded-lg bg-destructive/10 border border-destructive/20 text-xs text-destructive">
              <AlertCircle className="h-3.5 w-3.5 shrink-0" />
              <span className="flex-1">Something went wrong.</span>
              <button
                onClick={() => regenerate()}
                className="underline shrink-0 font-medium cursor-pointer"
              >
                Retry
              </button>
            </div>
          )}

          <div className="sticky bottom-0 z-1 mx-auto flex w-full max-w-3xl gap-2 border-t-0 bg-background px-2 pb-3 md:px-4 md:pb-4">
            <div className="relative flex w-full flex-col">
              <div className="rounded-2xl border border-border/30 bg-card/70 shadow-sm transition-shadow duration-300 focus-within:border-brand-500/40 focus-within:shadow-md">
                <textarea
                  ref={textareaRef}
                  value={input}
                  onChange={(e) => setInput(e.target.value)}
                  onKeyDown={handleKeyDown}
                  disabled={isStreaming}
                  rows={1}
                  placeholder="Ask a question about your feedback..."
                  className="w-full min-h-[2.5rem] resize-none bg-transparent px-4 pt-3 pb-1.5 text-[13px] leading-relaxed placeholder:text-muted-foreground/40 focus:outline-none disabled:opacity-50"
                />
                <div className="flex items-center justify-between px-3 pb-3">
                  <div className="flex items-center gap-1">
                    <span className="inline-flex items-center gap-1 rounded-md bg-muted px-2 py-0.5 text-[11px] text-muted-foreground">
                      <SiGooglegemini className="size-3" />
                      Gemini 2.5 Flash
                    </span>
                  </div>
                  {isStreaming ? (
                    <Button
                      size="icon"
                      variant="ghost"
                      className="h-7 w-7 rounded-lg cursor-pointer"
                      onClick={() => stop()}
                    >
                      <Square className="h-3.5 w-3.5 bg-destructive/10 text-destructive hover:bg-destructive/15" />
                    </Button>
                  ) : (
                    <Button
                      size="icon"
                      className={cn(
                        'h-10 w-10 rounded-full cursor-pointer transition-colors',
                        input.trim()
                          ? 'bg-primary text-background hover:bg-foreground/90'
                          : 'bg-muted text-muted-foreground/25',
                      )}
                      onClick={handleSend}
                      disabled={!input.trim()}
                    >
                      <Send className="h-3.5 w-3.5" />
                    </Button>
                  )}
                </div>
              </div>
            </div>
          </div>
        </div>
      </div>

      <div
        className={cn(
          'h-full shrink-0 border-l border-sidebar-border bg-sidebar transition-[width] duration-300 ease-[cubic-bezier(0.32,0.72,0,1)] overflow-hidden',
          sidebarCollapsed ? 'w-0 border-l-0' : 'w-60',
        )}
      >
        <div className="flex flex-col h-full min-h-0">
          <div className="flex items-center justify-between px-3 py-3">
            <p className="text-[10px] font-semibold uppercase tracking-[0.12em] text-sidebar-foreground/70">
              History
            </p>
            <Button
              size="icon"
              variant="ghost"
              className="h-7 w-7 cursor-pointer"
              onClick={() => setSidebarCollapsed(true)}
            >
              <PanelRightOpenIcon className="size-3.5 text-sidebar-foreground/60" />
            </Button>
          </div>

          <div className="px-2 pb-2 space-y-1">
            <Link
              href="/dashboard/chat"
              className="flex h-8 items-center gap-2 rounded-lg border border-sidebar-border px-2 text-[13px] text-sidebar-foreground/70 transition-colors duration-150 hover:bg-sidebar-accent/50 hover:text-sidebar-foreground"
            >
              <PenSquareIcon className="size-4" />
              <span className="font-medium">New chat</span>
            </Link>
          </div>

          <div className="min-h-0 flex-1 overflow-y-auto overscroll-contain">
            <ChatSidebar chatId={currentChatId} />
          </div>
        </div>
      </div>
    </div>
  );
}
